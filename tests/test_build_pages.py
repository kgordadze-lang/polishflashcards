# Priority 6 Phase 3 closes the version skew that Phases 1 and 2 accepted.
#
# Phases 1 and 2 bumped APP_VERSION without running the generator, so the committed
# pages kept an older footer version and these comparisons normalised that one label.
# Phase 3 regenerates, so committed bytes and freshly generated bytes are equal again
# and the normalisation is gone: exact equality is the contract once more.
FOOTER_VERSION_RE = re.compile(r"&middot; v\d+(?:\.\d+)* &middot;")
LD_BLOCK_RE = re.compile(r'<script type="application/ld\+json">(.*?)</script>', re.S)


def structured_data(markup):
    """The page's JSON-LD, parsed. Every generated page emits one array."""
    blocks = LD_BLOCK_RE.findall(markup)
    if len(blocks) != 1:
        raise AssertionError(f"expected exactly one JSON-LD block, found {len(blocks)}")
    entities = json.loads(blocks[0])
    if not isinstance(entities, list):
        raise AssertionError("JSON-LD is not the expected array of entities")
    return entities


def structured_entity(markup, type_name):
    """The single JSON-LD entity of that @type."""
    matches = [entity for entity in structured_data(markup)
               if entity.get("@type") == type_name]
    if len(matches) != 1:
        raise AssertionError(f"expected one {type_name} entity, found {len(matches)}")
    return matches[0]


def assert_generated_output_is_committed(case, committed, generated):
    """Committed bytes are exactly the bytes the generator emits.

    The footer label is asserted separately as well, so a page that somehow matched
    while carrying a stale version could not pass quietly. Pages without a learner
    footer - the two redirect stubs - carry no version label at all.
    """
    if FOOTER_VERSION_RE.search(generated):
        case.assertIn(
            f"&middot; v{build_pages.read_app_version()} &middot; {build_pages.BUILD_YEAR}"
            "</footer>", committed)
    else:
        case.assertNotIn("&middot; v", committed)
    case.assertEqual(committed, generated)

