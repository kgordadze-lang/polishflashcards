class OfficialRuntimeTests(unittest.TestCase):

    def test_the_released_bytes_are_what_the_approval_gated_path_produces(self):
        self.assertEqual(
            serialize_runtime(official_runtime()).encode("utf-8"),
            read_bytes(RUNTIME_PATH))

    def test_the_released_runtime_matches_the_locked_digest_and_length(self):
        released = read_bytes(RUNTIME_PATH)
        self.assertEqual(RUNTIME_SHA256, sha256(released))
        self.assertEqual(RUNTIME_BYTE_LENGTH, len(released))

    def test_regeneration_is_byte_identical_every_time(self):
        digests = set()
        for _ in range(3):
            frozen = T.freeze_editorial(
                live_corpus(), PATTERN_DATA_REVISION, repository_context())
            runtime = T.verified_runtime_from_frozen(frozen)
            digests.add(sha256(serialize_runtime(runtime).encode("utf-8")))
        self.assertEqual({RUNTIME_SHA256}, digests)

    def test_the_revision_is_derived_mechanically_not_chosen(self):
        """The tooling admits exactly one value, and refuses every other.

        ``freeze_editorial`` takes a previous baseline or none.  No prior
        frozen envelope is retained anywhere in this repository, so ``previous``
        is ``None`` and only revision 1 is admissible.
        """
        self.assertEqual(PATTERN_DATA_REVISION,
                         released_runtime()["patternDataRevision"])
        for rejected in (2, 3, 424242):
            with self.subTest(revision=rejected):
                with self.assertRaises(T.ValidationFailure) as raised:
                    T.freeze_editorial(
                        live_corpus(), rejected, repository_context())
                self.assertIn(
                    "FROZEN_INITIAL_REVISION",
                    {issue.code for issue in raised.exception.issues})
        for invalid in (0, -1):
            with self.subTest(revision=invalid):
                with self.assertRaises(T.ValidationFailure):
                    T.freeze_editorial(
                        live_corpus(), invalid, repository_context())

    def test_no_prior_frozen_priority_7_envelope_is_retained(self):
        retained = sorted(
            str(path.relative_to(ROOT))
            for path in ROOT.rglob("*.json")
            if path.is_file() and "frozen" in path.name.lower()
            and ".git" not in path.parts)
        self.assertEqual(["reports/priority-5-forward-frozen-baseline.json"],
                         retained)

    def test_the_released_runtime_is_not_the_superseded_g1_projection(self):
        self.assertNotEqual(SUPERSEDED_G1_RUNTIME_SHA256,
                            sha256(read_bytes(RUNTIME_PATH)))

    def test_the_identity_digests_are_exact(self):
        runtime = released_runtime()
        patterns = patterns_of(runtime)
        self.assertEqual(
            PATTERN_ID_SET_DIGEST, id_set_digest(p["id"] for p in patterns))
        self.assertEqual(
            LEMMA_ID_SET_DIGEST,
            id_set_digest(lemma["id"] for lemma in runtime["lemmas"]))
        self.assertEqual(
            EXAMPLE_ID_SET_DIGEST,
            id_set_digest(e["id"] for e in examples_of(runtime)))

    def test_pattern_and_lemma_identities_survived_the_content_completion(self):
        """The IDs are the Phase 4F-G1 ones: H2 added examples, not identities."""
