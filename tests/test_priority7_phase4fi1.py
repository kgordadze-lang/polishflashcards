def read(relative: str) -> str:
    return (ROOT / relative).read_text(encoding="utf-8")


def read_bytes(relative: str) -> bytes:
    return (ROOT / relative).read_bytes()


def git(*arguments: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", *arguments], cwd=ROOT, capture_output=True, text=True,
        check=False)


def git_blob(reference: str, relative: str) -> bytes | None:
    result = subprocess.run(
        ["git", "show", f"{reference}:{relative}"], cwd=ROOT,
        capture_output=True, check=False)
    return result.stdout if result.returncode == 0 else None


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def id_set_digest(identifiers) -> str:
    return hashlib.sha256(
        "\n".join(sorted(identifiers)).encode("utf-8")).hexdigest()


def serialize_runtime(runtime: dict) -> str:
    """The tooling's own file-writing convention, and the digest's definition."""
    return json.dumps(runtime, ensure_ascii=False, indent=2,
                      sort_keys=False) + "\n"


def walk_objects(value):
    if isinstance(value, dict):
        yield value
        for child in value.values():
            yield from walk_objects(child)
    elif isinstance(value, list):
        for child in value:
            yield from walk_objects(child)


def patterns_of(document) -> list:
    return [
        pattern
        for lemma in document["lemmas"]
        for meaning in lemma["meanings"]
        for pattern in meaning["patterns"]
    ]


def examples_of(document) -> list:
    return [example for pattern in patterns_of(document)
            for example in pattern.get("examples", [])]


