    def refuses(self, **overrides) -> bool:
        arguments = {"index_text": self.index, "worker_text": self.worker,
                     "runtime_bytes": self.runtime_bytes}
        arguments.update(overrides)
        try:
            I1.bundle(**arguments)
            return False
        except AssertionError:
            return True

