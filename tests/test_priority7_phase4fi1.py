def footprint() -> set[str]:
    """Every path this phase moved, whether committed or still in the tree."""
    touched = {
        line[3:].strip().strip('"')
        for line in git("status", "--porcelain").stdout.splitlines()
        if line.strip()}
    committed = git("diff", "--name-only", BASELINE_COMMIT, "HEAD")
    if committed.returncode == 0:
        touched |= {line.strip() for line in committed.stdout.splitlines()
                    if line.strip()}
    return touched


