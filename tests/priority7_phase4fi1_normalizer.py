# --------------------------------------------------------------------------
# Layer state
# --------------------------------------------------------------------------

def _edit_state(text: str, pre: str, post: str) -> str:
    """Report one pinned edit as ``absent``, ``complete`` or ``unrecognised``."""
    before, after = text.count(pre), text.count(post)
    # ``post`` may contain ``pre`` (an insertion keeps the anchor), so an
    # applied edit is recognised by the post-count and by the pre-count that
    # the post-text itself accounts for.
    accounted = post.count(pre)
    if after == 0 and before == 1:
        return "absent"
    if after == 1 and before == accounted:
        return "complete"
    return "unrecognised"


def phase_4fi1_file_state(path: str, text: str) -> str:
    """Report one shipping file's I1 layer as ``absent``/``complete``/``partial``."""
    edits = I1_EDITS.get(path)
    if edits is None:
        raise AssertionError(f"{path!r} is not a Phase 4F-I1 shipping path")
    states = {_edit_state(text, pre, post) for pre, post in edits}
    if states == {"absent"}:
        return "absent"
    if states == {"complete"}:
        return "complete"
    return "partial"


def phase_4fi1_runtime_state(runtime_bytes: bytes | None) -> str:
    """Report the runtime file as ``absent``, ``complete`` or ``partial``.

    ``complete`` means the exact pinned release bytes.  Anything else that
    exists at that path -- other bytes, a mutated digest, an extra private key,
    a different revision -- is ``partial`` and is never normalised away.
    """
    if runtime_bytes is None:
        return "absent"
    if not isinstance(runtime_bytes, (bytes, bytearray)):
        return "partial"
    if len(runtime_bytes) != PHASE_4FI1_RUNTIME_BYTE_LENGTH:
        return "partial"
    if hashlib.sha256(bytes(runtime_bytes)).hexdigest() != PHASE_4FI1_RUNTIME_SHA256:
        return "partial"
    return "complete"


def phase_4fi1_layer_state(index_text: str, worker_text: str,
                           runtime_bytes: bytes | None) -> str:
    """The whole-bundle verdict.  ``complete`` needs every component to agree."""
    states = {
        phase_4fi1_file_state("index.html", index_text),
        phase_4fi1_file_state("sw.js", worker_text),
        phase_4fi1_runtime_state(runtime_bytes),
    }
    if states == {"absent"}:
        return "absent"
    if states == {"complete"}:
        return "complete"
    return "partial"


# --------------------------------------------------------------------------
# The bundle
# --------------------------------------------------------------------------

@dataclasses.dataclass(frozen=True)
class Phase4FI1Bundle:
    """One validated view of the I1 transition, or of the tree before it.

    Constructed only through :func:`bundle`, which refuses a partial layer.  A
    caller therefore cannot normalise ``index.html`` without having proved, in
    the same breath, that the worker and the runtime moved with it.
    """

    index_text: str
    worker_text: str
    runtime_bytes: bytes | None
    state: str

    def without_activation(self, path: str) -> str:
        """Return ``path`` as it stood before Phase 4F-I1.

        Only the pinned strings are reversed, each exactly once.  Every other
        byte is passed through, so whatever the caller compares the result
        against still sees every other difference.
        """
        text = {"index.html": self.index_text, "sw.js": self.worker_text}.get(path)
        if text is None:
            raise AssertionError(f"{path!r} is not a Phase 4F-I1 shipping path")
        if self.state == "absent":
            return text
        for pre, post in I1_EDITS[path]:
            text = text.replace(post, pre, 1)
        if phase_4fi1_file_state(path, text) != "absent":   # pragma: no cover
            raise AssertionError(
                f"reverting the Phase 4F-I1 layer did not reach the pre-I1 {path}")
        return text

    def with_activation(self, path: str, baseline_text: str) -> str:
        """The exact inverse: apply the pinned layer to a pre-I1 file."""
        if phase_4fi1_file_state(path, baseline_text) != "absent":
            raise AssertionError(
                f"{path!r} does not carry the pre-I1 shape this layer applies to")
        text = baseline_text
        for pre, post in I1_EDITS[path]:
            text = text.replace(pre, post, 1)
        return text

    def is_exactly_the_i1_activation(self, path: str, baseline_text: str,
                                     live_text: str) -> bool:
        """True only when ``path``'s sole difference from baseline is the layer."""
        if path not in I1_EDITS:
            return False
        try:
            probe = dataclasses.replace(
                self,
                index_text=live_text if path == "index.html" else self.index_text,
                worker_text=live_text if path == "sw.js" else self.worker_text,
            )
            return probe.without_activation(path) == baseline_text
        except AssertionError:
            return False


def bundle(*, index_text: str, worker_text: str,
           runtime_bytes: bytes | None) -> Phase4FI1Bundle:
    """Validate the three core components together, or refuse.

    This is the all-or-nothing gate.  A tree in which the layer is present on
    some components and not others -- or in which the runtime exists with
    bytes other than the pinned release -- raises here, so no partly-activated
    tree can ever be normalised into looking like a clean pre-I1 baseline.
    """
    state = phase_4fi1_layer_state(index_text, worker_text, runtime_bytes)
    if state == "partial":
        raise AssertionError(
            "the Phase 4F-I1 activation layer is present on some but not all "
            "of the runtime document, index.html and sw.js, or the runtime "
            "bytes are not the pinned I1 release; the bundle is incomplete and "
            "must not be normalised away")
    return Phase4FI1Bundle(
        index_text=index_text, worker_text=worker_text,
        runtime_bytes=bytes(runtime_bytes) if runtime_bytes is not None else None,
        state=state)


# --------------------------------------------------------------------------
# Generator-owned output
# --------------------------------------------------------------------------

def without_phase_4fi1_version_stamp(text: str) -> str:
    """Return a generated page as it stood before the I1 version bump."""
    post, pre = I1_GENERATED_PAGE_EDIT[1], I1_GENERATED_PAGE_EDIT[0]
    if text.count(post) == 0 and text.count(pre) == 1:
        return text
    if text.count(post) != 1 or text.count(pre) != 0:
        raise AssertionError(
            "the generated page does not carry exactly one recognisable "
            "Phase 4F-I1 footer version stamp")
    return text.replace(post, pre, 1)


def is_exactly_the_i1_generated_page(baseline_text: str, live_text: str) -> bool:
    """True only when the page's sole difference is the footer version stamp."""
    try:
        return without_phase_4fi1_version_stamp(live_text) == baseline_text
    except AssertionError:
        return False


def is_exactly_the_i1_sitemap(baseline_text: str, live_text: str) -> bool:
    """True only when the sitemap differs by ``<lastmod>`` values alone.

    The generator moves a page's ``<lastmod>`` exactly when that page's bytes
    moved, so regenerating for the version stamp moves the 31 generated dates
    and carries the app shell's own date forward.  URL set, URL order and every
    other byte of the document must be identical, so an added, removed or
    reordered URL is still reported.
    """
    return _LASTMOD.sub("<lastmod/>", baseline_text) == \
        _LASTMOD.sub("<lastmod/>", live_text)


def is_phase_4fi1_path(path: str) -> bool:
    """True for the paths Phase 4F-I1 is entitled to move outside tests/reports."""
    return path in PHASE_4FI1_FOOTPRINT


def is_exactly_the_i1_transition(path: str, baseline_text: str, live_text: str,
                                 *, bundle: Phase4FI1Bundle | None = None) -> bool:
    """Classify one path's baseline->live difference as exactly the I1 layer.

    ``index.html`` and ``sw.js`` need the validated ``bundle``, because their
    layer is only meaningful as part of the whole transition.
    """
    if path in I1_EDITS:
        if bundle is None:
            return False
        return bundle.is_exactly_the_i1_activation(path, baseline_text, live_text)
    if path in PHASE_4FI1_GENERATED_PAGES:
        return is_exactly_the_i1_generated_page(baseline_text, live_text)
    if path == PHASE_4FI1_SITEMAP_PATH:
        return is_exactly_the_i1_sitemap(baseline_text, live_text)
    return False
