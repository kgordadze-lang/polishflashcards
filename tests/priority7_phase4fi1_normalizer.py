"""Phase 4F-I1 normalisation, shared by every historical Priority 7 suite.

Phase 4F-I1 is the **atomic activation** phase.  It is the first phase that
turns the dormant Priority 7 reference surface on, and it is deliberately one
indivisible transition across four kinds of file:

1. ``content/verb-patterns.json`` -- the official runtime document appears, with
   the exact bytes the approval-gated tooling produces from the approved corpus
   (``freeze_editorial`` then ``verified_runtime_from_frozen``);
2. ``index.html`` -- ``APP_VERSION`` advances ``8.10`` -> ``8.11`` and the one
   production loader activation is added;
3. ``sw.js`` -- the shell cache advances ``popolsku-v65`` -> ``popolsku-v66``,
   the helper and the runtime join the required precache inventory, and the
   runtime gets its own network-first classification while being excluded from
   the cache-first static inventory;
4. the 31 generator-owned pages and ``sitemap.xml`` -- regenerated by
   ``build_pages.py`` because the footer stamps ``APP_VERSION``.

Every Priority 7 phase before this one states, against its own pinned baseline,
some version of *the runtime file does not exist*, *the loader is dormant*,
*``APP_VERSION`` is 8.10*, *the shell cache is v65* or *no shipping file moved*.
Those were true statements about the tiers that had run.  Phase 4F-I1
legitimately supersedes all of them, so they are restated over the bundle with
the I1 layer removed -- exactly as Phase 4F-H3's wording claims are restated
over the shell with the H3 layer removed::

    bundle = I1.bundle(index_text=..., worker_text=..., runtime_bytes=...)
    self.assertEqual(git_blob("index.html"), bundle.without_activation("index.html"))

**All-or-nothing, by construction.**  There is no way to obtain a normalised
byte from this module without first building a :class:`Phase4FI1Bundle` over
*all three* core components together.  :func:`bundle` raises unless the layer is
uniformly ``absent`` or uniformly ``complete`` across:

* both pinned ``index.html`` edits;
* all six pinned ``sw.js`` edits;
* the runtime file -- present with **exactly** the pinned SHA-256, byte length
  and ``patternDataRevision``, or absent altogether.

So a tree that materialised the runtime but forgot the loader, that bumped the
version but not the cache, that shipped different runtime bytes, that shipped
the right bytes at the wrong revision, or that applied five of the six worker
edits is ``partial`` -- and ``partial`` is refused, never half-reverted.

**What it can hide, and therefore what it cannot.**  The two ``index.html``
edits and the six ``sw.js`` edits are pinned literal strings; every other byte
of both files is passed through untouched.  A caller comparing the normalised
text with its baseline blob therefore still sees, in full:

* a second loader activation, a different runtime URL, a preview/fixture URL,
  or an activation that survives reverting the pinned block;
* any other edit to ``index.html`` or ``sw.js``, anywhere, including an
  ``APP_VERSION`` or cache generation past the pinned I1 values;
* a missing, extra, mutated or wrongly-revisioned runtime file -- those are
  checked by digest, not by substitution, and a mismatch makes the whole bundle
  ``partial``;
* any missing required service-worker asset or changed classification, because
  those live in the pinned worker edits and a partial application is refused;
* H3 wording, recognition-only semantics, governance, corpus, audio and
  activity eligibility, none of which appear in any pinned string and none of
  which this module reads;
* an arbitrary generated-page change: :func:`is_exactly_the_i1_generated_page`
  admits only the single ``&middot; v8.10 &middot;`` -> ``&middot; v8.11
  &middot;`` footer stamp, and :func:`is_exactly_the_i1_sitemap` admits only
  ``<lastmod>`` movement with an identical URL set, order and structure.

This module is phase-owned and additive.  It imports nothing from the suites
that use it, opens no file, runs no subprocess and writes nothing.
"""

